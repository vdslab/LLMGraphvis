"""The database schema as Mermaid ER diagrams, generated from `models.py`.

A hand-drawn ER diagram in `specification/` drifted from the models within
months (ADR 0001): it lost three tables and the attribute provenance columns.
This module draws the column-level diagram from the SQLAlchemy metadata
instead, so the only hand-maintained part is which domain a table belongs to.
`backend/tests/test_schema_doc.py` fails when `schema.md` is stale or a table
has no domain.

Regenerate from `backend/` (or anywhere `common` is importable):

    python -m common.schema_doc
"""

from pathlib import Path
from typing import Dict, List, Tuple

from sqlalchemy import Column, Table, UniqueConstraint

from common.models import Base

SCHEMA_DOC_PATH = Path(__file__).with_name("schema.md")

# Each table in exactly one domain. One diagram per domain stays readable; a
# foreign key into another domain is drawn against a bare entity box.
DOMAINS: List[Tuple[str, str, Tuple[str, ...]]] = [
    (
        "グラフ本体",
        "ネットワークとその構造。サブグラフは親を指す独立したネットワークとして複製される。",
        ("networks", "nodes", "edges"),
    ),
    (
        "属性",
        "属性の定義（名前・型・意味・由来）と値。値は格納型ごとの子テーブルに分かれる。"
        "ノード側とエッジ側は同じ形をとる。",
        (
            "node_attributes",
            "node_attribute_values",
            "node_float_attribute_values",
            "node_text_attribute_values",
            "edge_attributes",
            "edge_attribute_values",
            "edge_float_attribute_values",
            "edge_text_attribute_values",
        ),
    ),
    (
        "利用者と会話",
        "利用者・チャット・メッセージと、エージェントの実行記録・トークン使用量。",
        ("users", "chats", "chat_messages", "tool_executions", "llm_usages"),
    ),
    (
        "会話中の入力",
        "利用者への質問（ask_user）とパラメータ調整パネル。どちらも回答を待つ間、状態を保持する。",
        ("analysis_inputs", "parameter_tunings"),
    ),
]


def _composite_uniques(table: Table) -> Dict[str, Tuple[str, ...]]:
    """column name -> the other columns of a multi-column UNIQUE it belongs to."""
    result: Dict[str, Tuple[str, ...]] = {}
    for constraint in table.constraints:
        if isinstance(constraint, UniqueConstraint) and len(constraint.columns) > 1:
            names = tuple(c.name for c in constraint.columns)
            for name in names:
                result[name] = names
    return result


def _column_line(column: Column, composite: Dict[str, Tuple[str, ...]]) -> str:
    keys = []
    if column.primary_key:
        keys.append("PK")
    if column.foreign_keys:
        keys.append("FK")
    if column.unique or column.name in composite:
        keys.append("UK")
    notes = []
    if column.name in composite:
        notes.append(f"unique({', '.join(composite[column.name])})")
    if column.nullable and not column.primary_key:
        notes.append("nullable")
    if column.comment:
        notes.append(column.comment)
    line = f"        {column.type.__visit_name__.upper()} {column.name}"
    if keys:
        line += " " + ", ".join(keys)
    if notes:
        line += ' "' + "; ".join(notes).replace('"', "'") + '"'
    return line


def _relationships(tables: Tuple[str, ...]) -> List[str]:
    """`parent ||--o{ child : "fk"` for every foreign key held by these tables."""
    lines = []
    for name in tables:
        table = Base.metadata.tables[name]
        for column in table.columns:
            for fk in column.foreign_keys:
                parent = fk.column.table.name
                one = "|o" if column.nullable else "||"
                many = "o|" if (column.unique or column.primary_key) else "o{"
                lines.append(f'    {parent} {one}--{many} {name} : "{column.name}"')
    return lines


def _diagram(tables: Tuple[str, ...]) -> List[str]:
    lines = ["```mermaid", "erDiagram"]
    lines += _relationships(tables)
    for name in tables:
        table = Base.metadata.tables[name]
        composite = _composite_uniques(table)
        lines.append(f"    {name} {{")
        lines += [_column_line(column, composite) for column in table.columns]
        lines.append("    }")
    lines.append("```")
    return lines


def render() -> str:
    lines = [
        "# データベーススキーマ（自動生成）",
        "",
        "<!-- Generated by `python -m common.schema_doc` from common/models.py."
        " Do not edit. -->",
        "",
        "`common/models.py` から生成した列レベルの ER 図。**手で編集しない。**"
        "モデルを変更したら `backend/` で `python -m common.schema_doc` を実行する。"
        "設計の意図は [4_Database.md]"
        "(../specification/2_Technical_Details/4_Database.md) にある。",
        "",
        "列の注記: `nullable` は NULL を許す列、`unique(...)` は複合一意制約。"
        "他の領域のテーブルは、外部キーの参照先として列なしで描かれる。",
    ]
    for title, summary, tables in DOMAINS:
        lines += ["", f"## {title}", "", summary, ""]
        lines += _diagram(tables)
    return "\n".join(lines) + "\n"


def unassigned_tables() -> List[str]:
    assigned = {name for _, _, tables in DOMAINS for name in tables}
    return sorted(set(Base.metadata.tables) - assigned)


if __name__ == "__main__":
    SCHEMA_DOC_PATH.write_text(render(), encoding="utf-8")
    print(f"Wrote {SCHEMA_DOC_PATH}")
